/**
 * Get daily quote based on date seed (day of year)
 */
export function getDailyQuote(quotesArray = SIX_HUNDRED_QUOTES, date = new Date()) {
  if (!quotesArray || quotesArray.length === 0) return null;
  const startOfYear = new Date(date.getFullYear(), 0, 0);
  const diff = date - startOfYear;
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  const index = Math.abs(dayOfYear * 7 + date.getFullYear()) % quotesArray.length;
  return quotesArray[index];
}

/**
 * Get a truly random quote from the 600 quotes (or filtered array)
 */
export function getRandomQuote(quotesArray = SIX_HUNDRED_QUOTES, excludeId = null) {
  if (!quotesArray || quotesArray.length === 0) return null;
  if (quotesArray.length === 1) return quotesArray[0];
  const candidates = excludeId ? quotesArray.filter(q => q.id !== excludeId) : quotesArray;
  const validList = candidates.length > 0 ? candidates : quotesArray;
  const randomIndex = Math.floor(Math.random() * validList.length);
  return validList[randomIndex];
}
